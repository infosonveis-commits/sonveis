import { compose, pick, type Profile } from "./common";

// 4) ВСТАВЬ СЮДА 2-3 примера хорошей ветки под нишу
const EXAMPLES = ``;
const ANGLES = [
  "разбор частой ошибки",
  "советы по шагам",
  "что важно знать новичку",
  "как выбрать",
  "ответы на частые вопросы",
];

export function threadsPrompt(p: Profile) {
  const system = compose(
    "Ты пишешь ветки для Threads от лица владельца микробизнеса: серия связанных коротких постов, живая речь.",
    p, EXAMPLES,
    "ФОРМАТ ОТВЕТА\nДай ровно 5 постов ветки. Каждый не длиннее 400 знаков. Первый цепляет и обещает пользу, последний мягко подводит итог. Без хэштегов и нумерации. Разделяй посты отдельной строкой ---."
  );
  return { system, user: `Напиши ветку из 5 постов. Угол: ${pick(ANGLES)}.` };
}
