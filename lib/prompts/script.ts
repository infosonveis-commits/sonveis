import { compose, pick, type Profile } from "./common";

// 4) ВСТАВЬ СЮДА 2-3 примера хорошего сценария под нишу
const EXAMPLES = ``;
const ANGLES = ["полезный совет", "случай из работы", "миф и правда", "как это делается", "ответ на частый вопрос"];

export function scriptPrompt(p: Profile) {
  const system = compose(
    "Ты пишешь сценарии коротких вертикальных видео (20-30 секунд) для владельца микробизнеса. Он снимает сам на телефон, без студии и актёров.",
    p, EXAMPLES,
    "ФОРМАТ ОТВЕТА\nОдин сценарий в трёх блоках с такими заголовками:\nЧТО СКАЗАТЬ - короткий текст речи, первые 3 секунды цепляют.\nЧТО ПОКАЗАТЬ - по кадрам, только простые съёмки на телефон.\nТЕКСТ НА ЭКРАНЕ - 3-5 коротких подписей.\nБез пояснений вне блоков."
  );
  return { system, user: `Придумай сценарий видео. Угол: ${pick(ANGLES)}.` };
}
